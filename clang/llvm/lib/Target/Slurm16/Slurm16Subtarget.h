//===-- Slurm16Subtarget.h - Define Subtarget for SLURM16 -------*- C++ -*-===//

#ifndef LLVM_LIB_TARGET_SLURM16_SLURM16SUBTARGET_H
#define LLVM_LIB_TARGET_SLURM16_SLURM16SUBTARGET_H

#include "Slurm16FrameLowering.h"
#include "Slurm16ISelLowering.h"
#include "Slurm16InstrInfo.h"
#include "Slurm16RegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include <memory>
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "Slurm16GenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class Slurm16Subtarget : public Slurm16GenSubtargetInfo {
  virtual void anchor();

  bool HasCondMov = false;

  Slurm16InstrInfo InstrInfo;
  Slurm16FrameLowering FrameLowering;
  Slurm16TargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  Slurm16Subtarget(const Triple &TT, const std::string &CPU,
                   const std::string &FS, const TargetMachine &TM);
  ~Slurm16Subtarget() override;

  Slurm16Subtarget &initializeSubtargetDependencies(StringRef CPU,
                                                    StringRef FS);

  /// Auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasCondMov() const { return HasCondMov; }

  const Slurm16FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const Slurm16InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const Slurm16RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const Slurm16TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;
};

} // namespace llvm

#endif
